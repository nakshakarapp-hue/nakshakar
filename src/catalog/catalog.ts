import type { RoofType, StairShape } from '../core/model/types';

export type PartShape = 'box' | 'cyl' | 'sphere' | 'cone';

/** One primitive of an object. Position and size are fractions of the object's width, depth and height. */
export interface Part {
  s: PartShape;
  x: number;
  y: number;
  z: number;
  w: number;
  d: number;
  h: number;
  c: string;
}

export interface CatalogObject {
  id: string;
  name: string;
  category: string;
  width: number;
  depth: number;
  height: number;
  colors: Record<string, string>;
  parts: Part[];
  /** Default height of the object's base above the floor. */
  mount?: number;
}

const b = (x: number, y: number, z: number, w: number, d: number, h: number, c: string): Part => ({
  s: 'box',
  x,
  y,
  z,
  w,
  d,
  h,
  c,
});
const cy = (x: number, y: number, z: number, w: number, d: number, h: number, c: string): Part => ({
  s: 'cyl',
  x,
  y,
  z,
  w,
  d,
  h,
  c,
});
const sp = (x: number, y: number, z: number, w: number, d: number, h: number, c: string): Part => ({
  s: 'sphere',
  x,
  y,
  z,
  w,
  d,
  h,
  c,
});

